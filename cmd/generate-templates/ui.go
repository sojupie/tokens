package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// The public component package forwards to model and renderer packages. Deriving
// these declarations keeps new primitives from requiring a second API inventory.
func generateUIFacade(check bool) error {
	set := token.NewFileSet()
	typeNames := map[string]bool{}
	modelFiles, err := filepath.Glob("forge/components/ui/internal/model/*.go")
	if err != nil {
		return err
	}
	renderFiles, err := filepath.Glob("forge/components/ui/internal/render/*.go")
	if err != nil {
		return err
	}
	type input struct {
		file  *ast.File
		owner string
	}
	var inputs []input
	for _, group := range []struct {
		paths []string
		owner string
	}{{modelFiles, "model"}, {renderFiles, "render"}} {
		for _, path := range group.paths {
			if strings.HasSuffix(path, "_test.go") {
				continue
			}
			file, err := parser.ParseFile(set, path, nil, parser.ParseComments)
			if err != nil {
				return err
			}
			inputs = append(inputs, input{file, group.owner})
			if group.owner == "model" {
				for _, d := range file.Decls {
					if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.TYPE {
						for _, sp := range g.Specs {
							typeNames[sp.(*ast.TypeSpec).Name.Name] = true
						}
					}
				}
			}
		}
	}
	var declarations []string
	qualify := func(expr ast.Expr) string {
		// Type names in model signatures become aliases through the model package;
		// field names, builtins and already-qualified external types stay unchanged.
		ast.Inspect(expr, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.SelectorExpr:
				return false
			case *ast.Ident:
				if typeNames[n.Name] {
					n.Name = "model." + n.Name
				}
			}
			return true
		})
		var b bytes.Buffer
		_ = format.Node(&b, set, expr)
		return b.String()
	}
	for _, in := range inputs {
		for _, d := range in.file.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				if in.owner != "model" || internalDeclaration(d.Doc) {
					continue
				}
				for _, sp := range d.Specs {
					switch sp := sp.(type) {
					case *ast.TypeSpec:
						if ast.IsExported(sp.Name.Name) {
							declarations = append(declarations, fmt.Sprintf("type %s = model.%s", sp.Name, sp.Name))
						}
					case *ast.ValueSpec:
						for _, name := range sp.Names {
							if ast.IsExported(name.Name) {
								declarations = append(declarations, fmt.Sprintf("%s %s = model.%s", strings.ToLower(d.Tok.String()), name, name))
							}
						}
					}
				}
			case *ast.FuncDecl:
				if d.Recv != nil || !ast.IsExported(d.Name.Name) || internalDeclaration(d.Doc) {
					continue
				}
				var parameters, args, results []string
				for _, field := range d.Type.Params.List {
					kind := qualify(field.Type)
					for _, name := range field.Names {
						parameters = append(parameters, name.Name+" "+kind)
						arg := name.Name
						if _, ok := field.Type.(*ast.Ellipsis); ok {
							arg += "..."
						}
						args = append(args, arg)
					}
				}
				if d.Type.Results != nil {
					for _, field := range d.Type.Results.List {
						results = append(results, qualify(field.Type))
					}
				}
				result := ""
				if len(results) == 1 {
					result = " " + results[0]
				} else if len(results) > 1 {
					result = " (" + strings.Join(results, ",") + ")"
				}
				ret := ""
				if len(results) > 0 {
					ret = "return "
				}
				declarations = append(declarations, fmt.Sprintf("func %s(%s)%s { %s%s.%s(%s) }", d.Name, strings.Join(parameters, ","), result, ret, in.owner, d.Name, strings.Join(args, ",")))
			}
		}
	}
	sort.Strings(declarations)
	source := []byte("// Code generated by go run ./cmd/generate-templates from Forge models and templates; DO NOT EDIT.\npackage ui\nimport (\n\"context\"\n\"io\"\n\"time\"\n\"github.com/a-h/templ\"\n\"github.com/sojupie/tokens/forge/components/ui/internal/model\"\n\"github.com/sojupie/tokens/forge/components/ui/internal/render\"\n)\n" + strings.Join(declarations, "\n"))
	// DateMonths and DateWeekdays are mutable API variables. Reading through
	// providers preserves replacement as well as in-place edits after the split.
	source = append(source, []byte("\nfunc init() { model.WeekdayLabels = func() []string { return DateWeekdays }; model.MonthLabels = func() []string { return DateMonths } }\n")...)
	source, err = cleanImports(source)
	if err != nil {
		return err
	}
	destination := "forge/components/ui/api_generated.go"
	if check {
		current, err := os.ReadFile(destination)
		if err != nil || !bytes.Equal(current, source) {
			return fmt.Errorf("%s is stale; run npm run generate:web", destination)
		}
		return nil
	}
	return os.WriteFile(destination, source, 0644)
}

// Internal helpers must be exported across model/render packages, but are not
// component API. The source directive keeps that distinction in generated facades.
func internalDeclaration(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, comment := range doc.List {
		if strings.Contains(comment.Text, "forge:internal") {
			return true
		}
	}
	return false
}
