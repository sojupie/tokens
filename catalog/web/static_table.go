// The static table exporter shares Catalog markup and assets with sites that
// supply their own token data and cannot run the Catalog HTTP handlers.
package web

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	webassets "github.com/sojupie/tokens/catalog/web/assets"
	webview "github.com/sojupie/tokens/catalog/web/internal/presentation"
	"github.com/sojupie/tokens/catalog/web/internal/render"
	"github.com/sojupie/tokens/forge/components"
	"github.com/sojupie/tokens/forge/components/ui"
	"github.com/sojupie/tokens/source/publish"
)

var hexColor = regexp.MustCompile(`^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$`)

type staticTokenTable struct {
	webview.StaticTokenTableLabels
	Groups []webview.TokenGroup
}

// ExportStaticTokenTable writes the table fragment and the assets it uses.
// Each top-level input group becomes a menu option.
func ExportStaticTokenTable(ctx context.Context, input io.Reader, assetsDir, out string) error {
	table := staticTokenTable{StaticTokenTableLabels: webview.StaticTokenTableLabels{
		AllLabel: "All tokens", SetLabel: "Token set", SearchLabel: "Search tokens",
		SearchPlaceholder: "Search", ControlsLabel: "Table controls",
		EmptyLabel: "No tokens match these filters.",
	}}
	decoder := json.NewDecoder(input)
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&table); err != nil {
		return fmt.Errorf("decode token table: %w", err)
	}
	if len(table.Groups) == 0 {
		return fmt.Errorf("token table has no groups")
	}
	var fragment bytes.Buffer
	requirements := ui.Assets{}
	if err := writeStaticTable(ui.WithAssets(ctx, requirements), &fragment, table); err != nil {
		return err
	}
	var modules []string
	for _, module := range webview.ComponentModuleOrder() {
		if requirements[module] {
			modules = append(modules, module)
			delete(requirements, module)
		}
	}
	if len(requirements) != 0 {
		return fmt.Errorf("unknown static table component modules: %v", requirements)
	}
	files := map[string][]byte{"table.html": fragment.Bytes()}
	if err := staticTableAssets(assetsDir, files, modules); err != nil {
		return err
	}
	for name, data := range files {
		path := filepath.Join(out, name)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(path, data, 0644); err != nil {
			return err
		}
	}
	return nil
}

func writeStaticTable(ctx context.Context, output *bytes.Buffer, table staticTokenTable) error {
	browser := webview.TokenBrowser{TableOnly: true, Static: &table.StaticTokenTableLabels}
	for i := range table.Groups {
		group := &table.Groups[i]
		count, err := prepareStaticGroup(group)
		if err != nil {
			return err
		}
		browser.Sets = append(browser.Sets, webview.TokenSet{Key: strconv.Itoa(i), Label: group.Name})
		browser.Count += count
	}
	browser.Selected = webview.TokenSet{All: true, Groups: table.Groups}
	output.WriteString(`<div class="tokens-static-table not-content" data-component-assets>`)
	if err := render.TokenBrowserView(publish.SubjectView{}, browser).Render(ctx, output); err != nil {
		return err
	}
	output.WriteString(`</div>`)
	return nil
}

func prepareStaticGroup(group *webview.TokenGroup) (int, error) {
	if group.Name == "" {
		return 0, fmt.Errorf("each token group needs a name")
	}
	for i := range group.Tokens {
		row := &group.Tokens[i]
		if row.Color != "" && !hexColor.MatchString(row.Color) {
			return 0, fmt.Errorf("invalid hex color for %s", row.SourceName)
		}
		if row.Shape != "" || row.Elevation != "" {
			return 0, fmt.Errorf("static table does not accept CSS values for %s", row.SourceName)
		}
		if row.Color != "" {
			// The shared swatch renderer calculates foreground contrast from RGBA.
			hex, _ := strconv.ParseUint(row.Color[1:7], 16, 24)
			alpha := 1.0
			if len(row.Color) == 9 {
				channel, _ := strconv.ParseUint(row.Color[7:], 16, 8)
				alpha = float64(channel) / 255
			}
			row.Color = fmt.Sprintf("rgba(%d, %d, %d, %g)", hex>>16, hex>>8&255, hex&255, alpha)
		}
	}
	count := len(group.Tokens)
	for i := range group.Children {
		children, err := prepareStaticGroup(&group.Children[i])
		if err != nil {
			return 0, err
		}
		count += children
	}
	return count, nil
}

func staticTableAssets(assetsDir string, files map[string][]byte, modules []string) error {
	// Starlight supplies the document theme. Keep the Catalog variables local to
	// the embed, including the default contrast variants of both themes.
	var css strings.Builder
	css.WriteString("/* Generated by tokens table-shell. Do not edit. */\n")
	writeTheme := func(name string) error {
		theme, err := os.ReadFile(filepath.Join(assetsDir, "themes", name+".css"))
		if err != nil {
			return fmt.Errorf("read generated %s theme: %w", name, err)
		}
		fmt.Fprintf(&css, "/* themes/%s.css */\n", name)
		scopedTheme := regexp.MustCompile(`:root([^{}]*)\{([^{}]*)\}`)
		for _, rule := range scopedTheme.FindAllStringSubmatch(string(theme), -1) {
			selector := strings.TrimSuffix(rule[1], " :is([data-component-assets],#component-preview)")
			if selector == "" {
				fmt.Fprintf(&css, ".tokens-static-table{%s}\n", rule[2])
			} else if strings.Contains(selector, "[data-contrast=default]") {
				fmt.Fprintf(&css, ":root%s .tokens-static-table{%s}\n", strings.ReplaceAll(selector, "[data-contrast=default]", ""), rule[2])
			}
		}
		return nil
	}
	if err := writeTheme("shared"); err != nil {
		return err
	}
	styles := []string{"site.css", "app.css", "token-table.css", "buttons.css", "bundles/common.css"}
	for _, module := range modules {
		if module == "common" {
			continue
		}
		if err := writeTheme(module); err != nil {
			return err
		}
		styles = append(styles, "bundles/"+module+".css")
	}
	css.WriteString("@scope (.tokens-static-table) {\n")
	for _, name := range styles {
		data, err := webassets.ReadStaticFile(name)
		if err != nil {
			return err
		}
		fmt.Fprintf(&css, "/* %s */\n", name)
		css.WriteString(strings.ReplaceAll(string(data), ":root", ":scope"))
		css.WriteByte('\n')
	}
	css.WriteString(`
:scope [hidden] { display: none !important; }
:scope code { font-family: monospace; }
:scope .tokens-token-description { overflow-wrap: anywhere; }
}
`)
	files["table.css"] = []byte(css.String())
	for _, name := range []string{"fonts/roboto-latin.woff2", "fonts/roboto-latin-ext.woff2", "fonts/OFL.txt", "fonts/MATERIAL-SYMBOLS-LICENSE.txt"} {
		data, err := webassets.ReadStaticFile(name)
		if err != nil {
			return err
		}
		files[name] = data
	}
	var script bytes.Buffer
	script.WriteString("/* Generated by tokens table-shell. Do not edit. */\n")
	moduleScripts, err := components.ScriptsFor(modules...)
	if err != nil {
		return err
	}
	scripts := append([]string{"motion.js", "buttons.js"}, moduleScripts...)
	scripts = append(scripts, "token-table.js", "static-token-table.js")
	for _, name := range scripts {
		data, err := webassets.ReadStaticFile(name)
		if err != nil {
			return err
		}
		fmt.Fprintf(&script, "/* %s */\n", name)
		script.Write(data)
		script.WriteString("\n;\n")
	}
	files["table.js"] = script.Bytes()
	return nil
}
