import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { build } from 'esbuild';
import { fileURLToPath } from "node:url";
import path from "node:path";

type BehaviorEntry = { source: string; output: string; aggregate: boolean };

const root = new URL("./", import.meta.url);

// Each public script stays a classic script. Pure source imports are bundled
// into that entry; no browser import graph or extra network request is introduced.
export async function compileBehavior(file: string, minifyWhitespace = true) {
  const result = await build({
    entryPoints: [fileURLToPath(new URL(file, root))],
    bundle: true, write: false, metafile: true, platform: 'browser', format: 'cjs',
    minifyWhitespace, legalComments: 'inline', logLevel: 'silent',
  });
  // Keep declarations private while preserving the existing guarded module.exports
  // used by standalone consumers and Node tests. format:iife would hide those exports.
  return { code: `(()=>{${result.outputFiles[0].text}})();\n`, inputs: Object.keys(result.metafile.inputs) };
}

// This checks file ownership, not the globals or execution order inside scripts.
export function validateScriptOwnership(modules: Record<string, { scripts?: string[] }>, inventory: string[]) {
  const files = new Set(inventory), owners = new Map<string, string>();
  for (const [id, module] of Object.entries(modules)) {
    for (const script of module.scripts || []) {
      if (!files.has(script)) throw Error(`Unknown component script: ${script}`);
      if (owners.has(script)) throw Error(`Duplicate script owner: ${script} (${owners.get(script)}, ${id})`);
      owners.set(script, id);
    }
  }
  for (const file of files)
    if (!owners.has(file)) throw Error(`Unowned component script: ${file}`);
}

// Build the maintained entries in manifest order, preserving public asset paths
// and the CSS cascade.
export async function componentAssets() {
  const modules: Record<string, { scripts?: string[] }> = JSON.parse(await readFile(new URL("modules.json", root), "utf8"));
  const behaviors: (string | BehaviorEntry)[] = JSON.parse(await readFile(new URL("behavior-sources.json", root), "utf8"));
  const entries = behaviors.map(entry => typeof entry === 'string'
    ? { source: entry, output: `runtime/${path.basename(entry).replace(/\.ts$/, ".js")}`, aggregate: true }
    : entry);
  const generatedScripts = entries.map(entry => entry.output);
  const standalone = (await readdir(new URL("static/", root)))
    // These two files are the shared button runtime and the legacy aggregate.
    .filter(name => name.endsWith(".js") && !["buttons.js", "components.js", ...generatedScripts].includes(name));
  validateScriptOwnership(modules, [...standalone, ...generatedScripts]);
  const outputs = new Map<string, string>();
  for (const [manifest, output, kind] of [
    ["style-sources.json", "static/components-base.css", "styles"],
    ["behavior-sources.json", "static/components.js", "behaviors"],
  ] as const) {
    const files: string[] = JSON.parse(await readFile(new URL(manifest, root), "utf8"));
    const banner = `/* Generated by forge/components/build-assets.ts from ${kind}/. Do not edit. */\n`;
    if (kind === 'behaviors') {
      const compiled = await Promise.all(entries.map(entry => compileBehavior(entry.source)));
      outputs.set(output, banner + compiled.filter((_, index) => entries[index].aggregate).map(result => result.code).join(''));
      for (const [index, entry] of entries.entries())
        outputs.set(`static/${entry.output}`, banner + compiled[index].code);
    } else {
      const sources = await Promise.all(files.map(file => readFile(new URL(file, root), 'utf8')));
      outputs.set(output, banner + sources.join(''));
    }
  }
  const motion = await compileBehavior("motion.ts");
  outputs.set("static/motion.cjs", "/* Generated from forge/components/motion.ts. Do not edit. */\n" + motion.code);
  const notices = await Promise.all(["LICENSE", "THIRD_PARTY_NOTICES.md"].map(name => readFile(new URL("../../" + name, root), "utf8")));
  outputs.set("static/NOTICE.txt", notices.join("\n\n"));
  return outputs;
}

export async function buildComponentAssets({ check = false } = {}) {
  for (const [file, content] of await componentAssets()) {
    const destination = new URL(file, root);
    if (check) {
      if ((await readFile(destination, "utf8")) !== content)
        throw new Error(`${file} is stale; run npm run build:components`);
    } else {
      await mkdir(new URL('./', destination), {recursive:true});
      await writeFile(destination, content);
    }
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await buildComponentAssets({ check: process.argv.includes("--check") });
}
